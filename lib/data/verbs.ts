// ── Pre-built lookup table: all conjugated forms → verb data ─
export interface VerbFormInfo {
  infinitive: string;
  form: "infinitive" | "finite" | "past_participle";
  isFinite: boolean;
  person?: 1 | 2 | 3;
  number?: "singular" | "plural";
  tense?: "present" | "simple_past";
  verbData: DutchVerb;
}

function buildVerbLookup(verbs: DutchVerb[]): Record<string, VerbFormInfo> {
  const lookup: Record<string, VerbFormInfo> = {};

  const add = (form: string, info: Omit<VerbFormInfo, "infinitive"> & { infinitive: string }) => {
    if (form && form !== "—" && !lookup[form]) {
      lookup[form] = info as VerbFormInfo;
    }
  };

  for (const v of verbs) {
    add(v.infinitive, { infinitive: v.infinitive, form: "infinitive", isFinite: false, verbData: v });
    add(v.presentSg1, { infinitive: v.infinitive, form: "finite", isFinite: true, person: 1, number: "singular", tense: "present", verbData: v });
    add(v.presentSg2, { infinitive: v.infinitive, form: "finite", isFinite: true, person: 2, number: "singular", tense: "present", verbData: v });
    add(v.presentSg2Inv, { infinitive: v.infinitive, form: "finite", isFinite: true, person: 2, number: "singular", tense: "present", verbData: v });
    add(v.presentSg3, { infinitive: v.infinitive, form: "finite", isFinite: true, person: 3, number: "singular", tense: "present", verbData: v });
    add(v.presentPl, { infinitive: v.infinitive, form: "finite", isFinite: true, person: 3, number: "plural", tense: "present", verbData: v });
    add(v.pastSg, { infinitive: v.infinitive, form: "finite", isFinite: true, number: "singular", tense: "simple_past", verbData: v });
    add(v.pastPl, { infinitive: v.infinitive, form: "finite", isFinite: true, number: "plural", tense: "simple_past", verbData: v });
    add(v.pastParticiple, { infinitive: v.infinitive, form: "past_participle", isFinite: false, verbData: v });
  }

  return lookup;
}

export const VERB_FORM_LOOKUP: Record<string, VerbFormInfo> = buildVerbLookup(DUTCH_VERBS);

// ── Helper: get verb by infinitive ───────────────────────────
export function getVerb(infinitive: string): DutchVerb | undefined {
  return DUTCH_VERBS.find((v) => v.infinitive === infinitive);
}

// ── Helper: get all separable verb prefixes ──────────────────
export const SEPARABLE_PREFIXES: Set<string> = new Set(
  DUTCH_VERBS.filter((v) => v.separable && v.separablePrefix).map((v) => v.separablePrefix!)
);

// ── Helper: lookup a finite form and get possible conjugation errors ─
export function getExpectedFiniteForm(
  verb: DutchVerb,
  person: 1 | 2 | 3,
  number: "singular" | "plural",
  inverted = false
): string {
  if (number === "plural") return verb.presentPl;
  if (person === 1) return verb.presentSg1;
  if (person === 2) return inverted ? verb.presentSg2Inv : verb.presentSg2;
  return verb.presentSg3;
}
