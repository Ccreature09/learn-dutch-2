export interface DutchVerb {
  infinitive: string;
  stem: string;
  translation: string;
  type: "weak" | "strong" | "modal" | "irregular" | "mixed";
  separable: boolean;
  separablePrefix?: string;
  baseVerb?: string;            // for separable verbs
  auxiliary: "hebben" | "zijn" | "both";
  // Present tense
  presentSg1: string;           // ik
  presentSg2: string;           // jij/je (normal)
  presentSg2Inv: string;        // jij/je after verb (inversion - no -t rule)
  presentSg3: string;           // hij/zij/het
  presentPl: string;            // wij/jullie/zij
  // Simple past (imperfectum)
  pastSg: string;
  pastPl: string;
  // Perfect tense helper
  pastParticiple: string;
  // Metadata
  isModal: boolean;
  frequency: "high" | "medium" | "low";
  difficulty: Difficulty;
  category: string[];
}

